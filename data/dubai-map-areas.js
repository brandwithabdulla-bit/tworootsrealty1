// Helper to look up an area by query
export function searchDubaiAreas(query) {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();

  return DUBAI_MAP_AREAS.filter(area => {
    if (area.name.toLowerCase().includes(q)) return true;
    if (area.shortName.toLowerCase().includes(q)) return true;
    if (area.aliases && area.aliases.some(alias => alias.includes(q) || q.includes(alias))) return true;
    if (area.type.toLowerCase().includes(q)) return true;
    if (area.category.toLowerCase().includes(q)) return true;
    return false;
  }).sort((a, b) => {
    // Exact or starting matches first
    const aExact = a.shortName.toLowerCase() === q || a.name.toLowerCase() === q || a.aliases.includes(q);
    const bExact = b.shortName.toLowerCase() === q || b.name.toLowerCase() === q || b.aliases.includes(q);
    if (aExact && !bExact) return -1;
    if (!aExact && bExact) return 1;

    const aStarts = a.shortName.toLowerCase().startsWith(q) || a.name.toLowerCase().startsWith(q);
    const bStarts = b.shortName.toLowerCase().startsWith(q) || b.name.toLowerCase().startsWith(q);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;

    return 0;
  });
}
